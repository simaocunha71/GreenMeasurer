#ifndef GM_ASPECT_H
#define GM_ASPECT_H

#include <pthread.h>
#include <stddef.h>
#include <sys/types.h>
#include <time.h>

#ifndef GM_MAX_SAMPLES
#define GM_MAX_SAMPLES 1000000
#endif

/* Root of the workload process tree (0 before it starts); read by workload-scoped metrics. */
extern volatile pid_t gm_workload_pid;

typedef enum {
    GM_KIND_COUNTER, /* cumulative reading; standard mode reports end - start */
    GM_KIND_GAUGE    /* instantaneous reading; standard mode reports the final reading */
} GmKind;

/* One metric of an aspect, as declared in the TOML file. */
typedef struct {
    const char *name;
    const char *unit;
    GmKind kind;
    int is_integer;
    double (*read)(void);         /* calls the user's function once */
    double (*sample)(size_t row); /* value stored by the sampling thread */
} GmMetric;

/* Synchronisation shared by one sampling thread and the runtime. */
typedef struct {
    pthread_mutex_t lock;
    pthread_cond_t wake;
    int stop;
    unsigned interval_ms;
    struct timespec origin;
} GmSampler;

void gm_sampler_init(GmSampler *sampler, unsigned interval_ms, const struct timespec *origin);
void gm_sampler_destroy(GmSampler *sampler);
void gm_sampler_request_stop(GmSampler *sampler);
int gm_sampler_stopping(GmSampler *sampler);
double gm_sampler_elapsed_ms(const GmSampler *sampler);
/* Sleeps for one interval; returns early when a stop is requested. */
void gm_sampler_wait(GmSampler *sampler);

/* Powercap calibration entry point of a device library (see intel_cpu_calibrate_powercap). It
 * calls back runTesting(), which the runtime provides. */
typedef int (*GmCalibratePowercapFn)(int ntimes, int core, const char *command,
                                     const char *language, const char *program,
                                     const char *calib_csv_file, const char *process_script,
                                     int min_powercap, int max_powercap, int time_out_limit,
                                     float temp_threshold, int variance, int memory);

/* An aspect generated by the weaver (one sampling thread in over-time mode). */
typedef struct {
    const char *name;
    size_t metric_count;
    const GmMetric *metrics;
    int (*setup)(void);    /* NULL when the TOML declares no setup */
    void (*teardown)(void); /* NULL when the TOML declares no teardown */
    int (*start)(const unsigned char *selected, unsigned interval_ms,
                 const struct timespec *origin);
    void (*stop)(void);    /* requests the stop and joins the thread */
    size_t (*count)(void); /* samples stored since the last start */
    double (*timestamp)(size_t row);
    int (*overflowed)(void);
    /* Optional hooks declared in the TOML; NULL when absent. */
    double (*thermal)(void);          /* CPU temperature used for thermal control, in C */
    int (*powercap_set)(int watts);   /* applies a limit (-1: the saved baseline); 0 on success */
    int (*powercap_restore)(void);    /* restores the state saved before the first limit */
    GmCalibratePowercapFn powercap_calibrate;
    int optional;                     /* continue with unavailable readings if setup fails */
} GmAspect;

/* Command-line flag generated for one metric: --<Aspect>.<Metric>. */
typedef struct {
    const char *flag;
    size_t aspect;
    size_t metric;
    int default_on;
} GmFlag;

/* Defaults taken from the TOML file; command-line arguments override them. */
typedef struct {
    const char *mode; /* "over-time" or "standard" */
    const char *command;
    const char *language;
    const char *program;
    const char *output;
    unsigned interval_ms;
    unsigned repetitions;
    unsigned sleep_seconds;
    unsigned variance;            /* thermal tolerance above the baseline, in C */
    const char *calibration_file; /* temperature baseline written by --temperature-calibration */
    const int *powercaps;         /* limits to measure, in watts; -1 means the saved baseline */
    size_t powercap_count;
    unsigned timeout_hours;
    const char *compile_command;
} GmConfig;

int gm_main(int argc, char **argv, const GmConfig *defaults,
            const GmAspect *aspects, size_t aspect_count,
            const GmFlag *flags, size_t flag_count);

#endif
